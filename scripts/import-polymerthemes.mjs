// Imports the free themes of https://polymerthemes.com (PolymerThemes v1.0.3, BSD license, © 2015 Polymer Themes)
// as Vellum theme specs: writes src/themes/polymer.js. Run: bin/dev node scripts/import-polymerthemes.mjs
//
// Each theme ships a CSS file (downloads/<id>.zip → <id>/<id>.css). What is taken from it:
//   page: `html, body` background (B) and color (text), `section[hero]` background (H), `h2` color (heading)
//   paper: the darker of B/H is the page (--v-bg), the lighter one the paper (--v-surface), as in Material where
//          raised surfaces are lighter
//   accents: `paper-button[<kind>][raised]` background / color for primary, secondary, success, info, warning, error
//   toolbar: --paper-toolbar-background / --paper-toolbar-color
// Everything else (secondary text, dividers, raised surfaces, toast, focus, shadows) is derived by deriveTheme().
import { writeFileSync } from 'node:fs'
import { inflateRawSync } from 'node:zlib'
import { luminance, normalize } from '../src/themes/color.js'

const IDS = ['candy', 'citric-flames', 'classical', 'dark-side', 'denim', 'everest', 'gelati', 'golden-goose', 'ice',
  'la-resistance', 'melon', 'seven-seas', 'sky', 'technology', 'the-times']

/** The one file we need out of a zip archive (stored or deflated entries). */
function unzip(buf, wanted) {
  let p = buf.length - 22
  while (p >= 0 && buf.readUInt32LE(p) !== 0x06054b50) p--
  let q = buf.readUInt32LE(p + 16)
  for (let n = buf.readUInt16LE(p + 10); n > 0; n--) {
    const method = buf.readUInt16LE(q + 10), size = buf.readUInt32LE(q + 20)
    const nameLen = buf.readUInt16LE(q + 28), extra = buf.readUInt16LE(q + 30), comment = buf.readUInt16LE(q + 32)
    const local = buf.readUInt32LE(q + 42), name = buf.toString('utf8', q + 46, q + 46 + nameLen)
    if (name === wanted) {
      const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28)
      const data = buf.subarray(start, start + size)
      return (method === 8 ? inflateRawSync(data) : data).toString('utf8')
    }
    q += 46 + nameLen + extra + comment
  }
  throw new Error(`${wanted} not in archive`)
}

const pick = (css, re, what) => {
  const m = re.exec(css)
  if (!m) throw new Error(`not found: ${what}`)
  return normalize(m[1].trim())
}

const specs = []
for (const id of IDS) {
  const res = await fetch(`https://polymerthemes.com/downloads/${id}.zip`)
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`)
  const css = unzip(Buffer.from(await res.arrayBuffer()), `${id}/${id}.css`)
  const body = /html, body \{([^}]*)\}/.exec(css)[1]
  const B = pick(body, /background-color:\s*([^;]+);/, 'body background')
  const text = pick(body, /(?:^|;)\s*color:\s*([^;]+);/, 'body color')
  const H = pick(css, /section\[hero\] \{ background-color:\s*([^;]+);/, 'hero')
  let heading = text
  try { heading = pick(css, /\nh2 \{[^}]*?color:\s*([^;]+);/, 'h2') } catch { /* same as the text */ }
  const [bg, surface] = luminance(B) <= luminance(H) ? [B, H] : [H, B]
  const spec = { bg, surface, text, heading }
  for (const kind of ['primary', 'secondary', 'success', 'info', 'warning', 'error']) {
    const m = new RegExp(`paper-button\\[${kind}\\]\\[raised\\] \\{ background-color:\\s*([^;]+);\\s*color:\\s*([^;]+);`).exec(css)
    if (!m) throw new Error(`${id}: no raised ${kind} button`)
    spec[kind] = normalize(m[1]); spec[`on-${kind}`] = normalize(m[2])
  }
  spec.toolbar = pick(css, /--paper-toolbar-background:\s*([^;]+);/, 'toolbar')
  spec['on-toolbar'] = pick(css, /--paper-toolbar-color:\s*([^;]+);/, 'toolbar color')
  const name = id.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ')
  specs.push({ id, name, group: 'polymer', source: `https://polymerthemes.com/${id}/`, spec })
  console.log(id.padEnd(14), JSON.stringify(spec))
}

const out = `// Generated by scripts/import-polymerthemes.mjs — do not edit by hand.
// The free themes of https://polymerthemes.com (PolymerThemes v1.0.3, © 2015 Polymer Themes, BSD license; see NOTICE),
// as Vellum theme specs: page, paper, text and accent colors come from each theme's CSS, the rest is derived.
export const POLYMER_THEMES = ${JSON.stringify(specs, null, 2).replace(/"([a-z]+)":/g, '$1:')}
`
writeFileSync('src/themes/polymer.js', out)
console.log(`src/themes/polymer.js: ${specs.length} themes`)
